# ------------------------------------------------------------------ 6 power query
dedupe = ('#"Removed blank IDs"     = Table.SelectRows(typed, each [customer_id] <> null and [customer_id] <> ""),\n'
          '#"Added completeness"    = Table.AddColumn(#"Removed blank IDs", "__filled", each List.NonNullCount(Record.FieldValues(_)), Int64.Type),\n'
          '#"Sorted by completeness" = Table.Buffer(Table.Sort(#"Added completeness", {{"customer_id", Order.Ascending}, {"__filled", Order.Descending}})),\n'
          '#"Kept most complete row" = Table.Distinct(#"Sorted by completeness", {"customer_id"}),\n'
          '#"Removed stub rows"     = Table.SelectRows(#"Removed helper", each not ([email] = null and [join_date] = null and [segment] = null))')
